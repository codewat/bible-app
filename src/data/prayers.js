// Helper to get today's default Rosary mystery based on day of week
export function getTodaysMysteryKey() {
  const day = new Date().getDay(); // 0 is Sunday, 1 is Monday, etc.
  if (day === 1 || day === 6) return 'joyful'; // Monday, Saturday
  if (day === 2 || day === 5) return 'sorrowful'; // Tuesday, Friday
  if (day === 4) return 'luminous'; // Thursday
  return 'glorious'; // Wednesday (3), Sunday (0)
}

